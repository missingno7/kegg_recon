void animate(void) { if (sprite_instance_count) draw_animated_sprites(); }

/* Advance each sprite animation and append visible frames to the draw list. */
void draw_animated_sprites(void)
{
    sprite_current = sprite_animations;
    for (sprite_removal_index = 0; sprite_removal_index < sprite_instance_count; sprite_removal_index++) {
        if (sprite_current->follows_player) {
            sprite_current->x = racket_object->x;
            sprite_current->y = racket_object->y;
        } else if (sprite_current->animation_delay == 0) {
            sprite_current->x += sprite_current->velocity_x;
            sprite_current->y += sprite_current->velocity_y;
        } else {
            sprite_current->animation_delay--;
        }
        if (--sprite_current->frame_delay <= 0) {
            temp = (++sprite_current->current_frame)->duration_or_delta;
            if (temp < 0) {
                if (sprite_current->signals_bonus) player_key_flags->control_flags |= CONTROL_GUARD_ANIMATION;
                if (sprite_current->remove_after_animation) {
                    remove_animated_sprite();
                    continue;
                }
                sprite_current->current_frame += temp;
                temp = sprite_current->current_frame->duration_or_delta;
            }
            sprite_current->frame_delay = temp;
        }
        sprite_frame_pointer = sprite_current->sprite_bank + sprite_current->current_frame->image_offset;
        if (sprite_current->check_screen_bounds) {
            collision_box_a_left = sprite_current->x;
            collision_box_a_top = sprite_current->y;
            get_sprite_bounds(&collision_box_a_left, sprite_frame_pointer);
            if (sprite_current->x > SPRITE_CULL_RIGHT_LIMIT || sprite_current->x < -SPRITE_CULL_MARGIN ||
                sprite_current->y > SPRITE_CULL_BOTTOM_LIMIT || sprite_current->y < -SPRITE_CULL_MARGIN) {
                remove_animated_sprite();
                continue;
            }
        }
        image_buffer_cursor->sprite_or_frame = sprite_frame_pointer;
        image_buffer_cursor->x = sprite_current->x;
        image_buffer_cursor->y = sprite_current->y;
        image_buffer_cursor->flags = 0;
        image_buffer_cursor++;
        sprite_current++;
    }
}

void remove_animated_sprite(void)
{
    --sprite_instance_count;
    if (sprite_removal_index != sprite_instance_count)
        memcpy(sprite_current, sprite_current + 1, (sprite_instance_count - sprite_removal_index) * ANIMATED_SPRITE_BYTES);
    --sprite_removal_index;
}

void spawn_animated_sprite(int x, int y, int velocity_x, int velocity_y, int sprite_bank, int first_frame, int animation_flags)
{
    if (sprite_instance_count < MAX_ANIMATED_SPRITES) {
        sprite_current = sprite_animations;
        sprite_current += sprite_instance_count;
        sprite_current->x = x;
        sprite_current->y = y;
        sprite_current->velocity_x = velocity_x;
        sprite_current->velocity_y = velocity_y;
        if (animation_flags & SPRITE_USE_FIRST_FRAME) {
            sprite_current->frame_delay = SPRITE_FIRST_FRAME_HOLD;
            sprite_current->current_frame = first_frame;
        } else {
            sprite_current->frame_delay = 0;
            sprite_current->current_frame = first_frame - SPRITE_FRAME_BYTES;
        }
        sprite_current->sprite_bank = sprite_bank;
        sprite_current->animation_delay = animation_flags >> SPRITE_ANIMATION_DELAY_SHIFT;
        sprite_current->follows_player = animation_flags >> SPRITE_FOLLOW_RACKET_SHIFT;
        sprite_current->signals_bonus = animation_flags >> SPRITE_SIGNALS_BONUS_SHIFT;
        sprite_current->check_screen_bounds = animation_flags >> SPRITE_CHECK_SCREEN_BOUNDS_SHIFT;
        sprite_current->remove_after_animation = animation_flags;
        sprite_instance_count++;
    }
}
