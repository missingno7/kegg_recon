void recalculate_joystick_thresholds(void) {
    primary_joystick.axis_timing[JOY_X_LEFT_THRESHOLD] = (primary_joystick.axis_timing[JOY_X_MINIMUM] + primary_joystick.axis_timing[JOY_X_CENTER]) >> 1;
    secondary_joystick.axis_timing[JOY_X_LEFT_THRESHOLD] = (secondary_joystick.axis_timing[JOY_X_MINIMUM] + secondary_joystick.axis_timing[JOY_X_CENTER]) >> 1;
    primary_joystick.axis_timing[JOY_X_RIGHT_THRESHOLD] = (primary_joystick.axis_timing[JOY_X_CENTER] + primary_joystick.axis_timing[JOY_X_MAXIMUM]) >> 1;
    secondary_joystick.axis_timing[JOY_X_RIGHT_THRESHOLD] = (secondary_joystick.axis_timing[JOY_X_CENTER] + secondary_joystick.axis_timing[JOY_X_MAXIMUM]) >> 1;
    primary_joystick.axis_timing[JOY_Y_TOP_THRESHOLD] = (primary_joystick.axis_timing[JOY_Y_MINIMUM] + primary_joystick.axis_timing[JOY_Y_CENTER]) >> 1;
    secondary_joystick.axis_timing[JOY_Y_TOP_THRESHOLD] = (secondary_joystick.axis_timing[JOY_Y_MINIMUM] + secondary_joystick.axis_timing[JOY_Y_CENTER]) >> 1;
    primary_joystick.axis_timing[JOY_Y_BOTTOM_THRESHOLD] = (primary_joystick.axis_timing[JOY_Y_CENTER] + primary_joystick.axis_timing[JOY_Y_MAXIMUM]) >> 1;
    secondary_joystick.axis_timing[JOY_Y_BOTTOM_THRESHOLD] = (secondary_joystick.axis_timing[JOY_Y_CENTER] + secondary_joystick.axis_timing[JOY_Y_MAXIMUM]) >> 1;
    joystick_max_axis_time = primary_joystick.axis_timing[JOY_X_RIGHT_THRESHOLD];
    if (primary_joystick.axis_timing[JOY_Y_BOTTOM_THRESHOLD] > joystick_max_axis_time) joystick_max_axis_time = primary_joystick.axis_timing[JOY_Y_BOTTOM_THRESHOLD];
    if (secondary_joystick.axis_timing[JOY_X_RIGHT_THRESHOLD] > joystick_max_axis_time) joystick_max_axis_time = secondary_joystick.axis_timing[JOY_X_RIGHT_THRESHOLD];
    if (secondary_joystick.axis_timing[JOY_Y_BOTTOM_THRESHOLD] > joystick_max_axis_time) joystick_max_axis_time = secondary_joystick.axis_timing[JOY_Y_BOTTOM_THRESHOLD];
}

/* Capture neutral X/Y samples, then seed min/max bounds around the center. */
void initialize_joystick_calibration(void) {
    primary_joystick.axis_timing[JOY_X_CURRENT] = 0;
    primary_joystick.axis_timing[JOY_Y_CURRENT] = 0;
    secondary_joystick.axis_timing[JOY_X_CURRENT] = 0;
    secondary_joystick.axis_timing[JOY_Y_CURRENT] = 0;
    joystick_calibration_active = 1;
    poll_joystick_ports();
    poll_joystick_ports();
    joystick_calibration_active = 0;
    primary_joystick.axis_timing[JOY_X_MINIMUM] = 0;
    primary_joystick.axis_timing[JOY_Y_MINIMUM] = 0;
    secondary_joystick.axis_timing[JOY_X_MINIMUM] = 0;
    secondary_joystick.axis_timing[JOY_Y_MINIMUM] = 0;
    primary_joystick.axis_timing[JOY_X_CENTER] = primary_joystick.axis_timing[JOY_X_CURRENT];
    primary_joystick.axis_timing[JOY_Y_CENTER] = primary_joystick.axis_timing[JOY_Y_CURRENT];
    secondary_joystick.axis_timing[JOY_X_CENTER] = secondary_joystick.axis_timing[JOY_X_CURRENT];
    secondary_joystick.axis_timing[JOY_Y_CENTER] = secondary_joystick.axis_timing[JOY_Y_CURRENT];
    primary_joystick.axis_timing[JOY_X_MAXIMUM] = primary_joystick.axis_timing[JOY_X_CURRENT] * 2;
    primary_joystick.axis_timing[JOY_Y_MAXIMUM] = primary_joystick.axis_timing[JOY_Y_CURRENT] * 2;
    secondary_joystick.axis_timing[JOY_X_MAXIMUM] = secondary_joystick.axis_timing[JOY_X_CURRENT] * 2;
    secondary_joystick.axis_timing[JOY_Y_MAXIMUM] = secondary_joystick.axis_timing[JOY_Y_CURRENT] * 2;
    recalculate_joystick_thresholds();
    outp(JOYSTICK_GAMEPORT, 0xff);
}
