#define scan_code current_scan_code
#define JOYSTICK_GAMEPORT 0x201
#define JOYSTICK_PROBE_POLL_LIMIT 1000
#define JOYSTICK_MIN_AXIS_TICKS 0x20

enum JoystickTimingSlot {
    JOY_X_CURRENT,
    JOY_Y_CURRENT,
    JOY_X_LEFT_THRESHOLD,
    JOY_X_RIGHT_THRESHOLD,
    JOY_Y_TOP_THRESHOLD,
    JOY_Y_BOTTOM_THRESHOLD,
    JOY_X_MINIMUM,
    JOY_X_CENTER,
    JOY_X_MAXIMUM,
    JOY_Y_MINIMUM,
    JOY_Y_CENTER,
    JOY_Y_MAXIMUM
};

