void aitune(void)
{
    enemy_max_health = ((struct EnemyStageTuning *)((unsigned char *)gameplay_tuning_by_stage + (difficulty_tier_index << 4)))->enemy_health_max;
    enemy_health_current = enemy_max_health;
    last_displayed_enemy_health = enemy_health_current;
    enemy_pattern = ((struct EnemyStageTuning *)((unsigned char *)gameplay_tuning_by_stage + ((difficulty_tier_index << 2) << 2)))->enemy_pattern;
    enemy_attack_interval = ((struct EnemyStageTuning *)((unsigned char *)gameplay_tuning_by_stage + ((difficulty_tier_index << 2) << 2)))->enemy_attack_interval;
    attack_cooldown = enemy_attack_interval;
    attack_delay = ((struct EnemyStageTuning *)((unsigned char *)gameplay_tuning_by_stage + ((difficulty_tier_index << 2) << 2)))->attack_delay;
    enemy_attack_timer = 0;
    attack_frame_count = 7;
    enemy_fire_acceleration = 0xf;
}

void initialize_level_hud(void)
{
    set_mouse_bounds(4, 16, 4, 0x95);
    move_mouse_to(4, 0x52);
    for (temp = 0; temp < 4; ++temp)
        update_mouse();
    total_level_time = LEVEL_TIME_LIMIT_SECONDS;
    remaining_level_time = total_level_time;
    last_displayed_time = remaining_level_time;
}

void update_level_hud(void)
{
    if (remaining_level_time <= 0) {
        remaining_level_time = 0;
        set_mouse_bounds(history_mouse_x_0, mouse_y_sample_0, history_mouse_x_0, mouse_y_sample_0);
    }
    if (remaining_level_time != last_displayed_time) {
        last_displayed_time = remaining_level_time;
        vga_state.viewport_bottom_or_height = old_display_mode;
        fill_clipped_vga_rectangle(drawpage, ((remaining_level_time * 0x6f) / total_level_time) + 0x1c, 0xb3, 0x8b, 0xb9, 0);
        fill_clipped_vga_rectangle(page_idx, ((remaining_level_time * 0x6f) / total_level_time) + 0x1c, 0xb3, 0x8b, 0xb9, 0);
        vga_state.viewport_bottom_or_height = LEVEL_HUD_BOTTOM;
        for (temp = 0; temp < VGA_PALETTE_COMPONENT_BYTES; temp += 3) {
            if ((*(unsigned char *)(unsigned char *)(vga_buffer_base + temp) += 3) > VGA_DAC_MAX_COMPONENT) {
                *(unsigned char *)(unsigned char *)(vga_buffer_base + temp) = VGA_DAC_MAX_COMPONENT;
            }
        }
        hud_flash_ticks = 1;
        submit_audio_request(AUDIO_CUE_TIMER_UPDATE);
    }
    if (enemy_health_current != last_displayed_enemy_health) {
        if (enemy_health_current < 0) {
            enemy_health_current = 0;
            enemy_attack_timer = ENEMY_DEFEAT_SETTLE_TICKS;
        }
        last_displayed_enemy_health = enemy_health_current;
        vga_state.viewport_bottom_or_height = old_display_mode;
        fill_clipped_vga_rectangle(drawpage, ((enemy_health_current * 0x6f) / enemy_max_health) + 0xb4, 0xb3, 0x123, 0xb9, 0);
        fill_clipped_vga_rectangle(page_idx, ((enemy_health_current * 0x6f) / enemy_max_health) + 0xb4, 0xb3, 0x123, 0xb9, 0);
        vga_state.viewport_bottom_or_height = LEVEL_HUD_BOTTOM;
        hud_flash_ticks += 8;
        submit_audio_request(AUDIO_CUE_ENEMY_HIT);
    }
    if (hud_flash_ticks > 0) {
        write_dac_palette((void *)vga_buffer_base, 0, VGA_DAC_ENTRY_COUNT, -hud_flash_ticks);
        --hud_flash_ticks;
    }
}

void firein(void)
{
    if (remaining_level_time > 0) {
        if (!player_shot_button_latch && mouse_btn != MOUSE_BUTTON_BOTH) {
            if (mouse_btn != mouse_btn_old && (mouse_btn & MOUSE_BUTTON_LEFT) == MOUSE_BUTTON_LEFT) {
                submit_audio_request(AUDIO_CUE_PLAYER_SHOT);
                spawn_auxiliary_projectile(PROJECTILE_TARGET_ENEMY, PLAYER_SHOT_SINGLE_DAMAGE, mouse_x_average_recent, mouse_y_mean_recent, PLAYER_SHOT_SINGLE_SPEED, 0, (int)player_projectile_animation_frames);
                history_mouse_x_0 -= 7;
                player_shot_button_latch = 1;
            } else if (mouse_btn != mouse_btn_old && mouse_btn & MOUSE_BUTTON_RIGHT) {
                submit_audio_request(AUDIO_CUE_PLAYER_SHOT);
                spawn_auxiliary_projectile(PROJECTILE_TARGET_ENEMY, PLAYER_SHOT_SPREAD_DAMAGE, mouse_x_average_recent, mouse_y_mean_recent, PLAYER_SHOT_SPREAD_SPEED, PLAYER_SHOT_SPREAD_SIDE_SPEED, (int)player_projectile_animation_frames);
                spawn_auxiliary_projectile(PROJECTILE_TARGET_ENEMY, PLAYER_SHOT_SPREAD_DAMAGE, mouse_x_average_recent, mouse_y_mean_recent, PLAYER_SHOT_SPREAD_SPEED, -PLAYER_SHOT_SPREAD_SIDE_SPEED, (int)player_projectile_animation_frames);
                history_mouse_x_0 -= 7;
                player_shot_button_latch = 1;
            }
        } else {
            player_shot_button_latch = 0;
        }
    }
    image_buffer_cursor->sprite_or_frame = (int)(game_sprite_base + PLAYER_SHOT_SPRITE_OFFSET);
    image_buffer_cursor->x = mouse_x_average_recent;
    image_buffer_cursor->y = mouse_y_mean_recent;
    image_buffer_cursor->flags = 0;
    ++image_buffer_cursor;
}

void update_auxiliary_projectiles(void) { if (enemy_projectile_count) move_auxiliary_projectiles(); }

/* Move enemy bolts, test them against the racket and brick field, and draw survivors. */
void move_auxiliary_projectiles(void)
{
    struct BobFrameMetrics *target_bounds;
    struct BobFrameMetrics *shot_frame_info;
    bolt_cursor = auxiliary_projectiles;
    for (projectile_index = 0; projectile_index < enemy_projectile_count; ++projectile_index) {
        bolt_cursor->x += bolt_cursor->velocity_x;
        bolt_cursor->y += bolt_cursor->velocity_y;
        next_packed_table_value(&bolt_cursor->frame_info, &bolt_cursor->frame_offset);
        shot_frame_info = (struct BobFrameMetrics *)(*(int *)bolt_cursor->frame_offset + bolt_cursor->sprite_data);
        if ((bolt_cursor->x >> 4) > 0x150 || (bolt_cursor->x >> 4) < -0x10 || (bolt_cursor->y >> 4) > 0xd8 || (bolt_cursor->y >> 4) < -0x10) {
            remove_auxiliary_projectile();
            continue;
        }
        if (!bolt_cursor->target_type) {
            target_bounds = (struct BobFrameMetrics *)(game_sprite_base + ENEMY_IDLE_SPRITE_OFFSET);
            if (frames_intersect_inset(*target_bounds, ENEMY_DRAW_X, ENEMY_DRAW_Y, *shot_frame_info, bolt_cursor->x >> 4, bolt_cursor->y >> 4, 0xa, 0, 0xa, 0) == -1) {
                enemy_health_current -= bolt_cursor->damage;
                spawn_animated_sprite(bolt_cursor->x >> 4, bolt_cursor->y >> 4, bolt_cursor->velocity_x >> 6, bolt_cursor->velocity_y >> 6, (int)game_sprite_base, (int)bolt_impact_animation_frames, 1);
                remove_auxiliary_projectile();
                continue;
            }
            if (((bolt_cursor->x >> 4) + 5) > open_brick_x_by_row[bolt_cursor->y >> 4]) {
                submit_audio_request(AUDIO_CUE_BRICK_HIT);
                spawn_animated_sprite(bolt_cursor->x >> 4, bolt_cursor->y >> 4, 0, 0, (int)game_sprite_base, (int)bolt_impact_animation_frames, 1);
                remove_auxiliary_projectile();
                continue;
            }
        } else {
            target_bounds = (struct BobFrameMetrics *)(game_sprite_base + PLAYER_SHOT_SPRITE_OFFSET);
            if (frames_intersect_inset(*target_bounds, mouse_x_average_recent, mouse_y_mean_recent, *shot_frame_info, (bolt_cursor->x >> 4) + 8, bolt_cursor->y >> 4, 4, 4, 4, 4) == -1) {
                if (remaining_level_time > 0) {
                    remaining_level_time -= bolt_cursor->damage;
                }
                spawn_animated_sprite(bolt_cursor->x >> 4, bolt_cursor->y >> 4, 0, 0, (int)game_sprite_base, (int)bolt_impact_animation_frames, 1);
                remove_auxiliary_projectile();
                continue;
            }
        }
        image_buffer_cursor->sprite_or_frame = shot_frame_info;
        image_buffer_cursor->x = (unsigned short)(bolt_cursor->x >> 4);
        image_buffer_cursor->y = (unsigned short)(bolt_cursor->y >> 4);
        image_buffer_cursor->flags = 0;
        ++image_buffer_cursor;
        ++bolt_cursor;
    }
}

void remove_auxiliary_projectile(void)
{
    --enemy_projectile_count;
    if (projectile_index != enemy_projectile_count)
        memcpy(bolt_cursor, bolt_cursor + 1, (enemy_projectile_count - projectile_index) * sizeof(*bolt_cursor));
    --projectile_index;
}

void spawn_auxiliary_projectile(int target_type, int damage_amount, int x, int y, int velocity_x, int velocity_y, int frame_offset)
{
    if (enemy_projectile_count < AUXILIARY_PROJECTILE_CAPACITY) {
        bolt_cursor = auxiliary_projectiles;
        bolt_cursor += enemy_projectile_count;
        bolt_cursor->target_type = target_type;
        bolt_cursor->damage = damage_amount;
        bolt_cursor->x = x << 4;
        bolt_cursor->y = y << 4;
        bolt_cursor->velocity_x = velocity_x;
        bolt_cursor->velocity_y = velocity_y;
        bolt_cursor->frame_info = 0;
        bolt_cursor->frame_offset = (unsigned char *)(frame_offset - 8);
        bolt_cursor->sprite_data = game_sprite_base;
        ++enemy_projectile_count;
    }
}

void update_enemy_attack_cycle(void)
{
    int monster_x;
    int monster_y;
    int projectile_dx;
    int projectile_dy;
    int emitted_effect;
    monster_x = ENEMY_BODY_ANCHOR_X;
    monster_y = ENEMY_BODY_ANCHOR_Y;
    emitted_effect = 0;
    if (enemy_health_current > 0) {
        --enemy_attack_timer;
        if (enemy_attack_timer <= 0) {
            image_buffer_cursor->sprite_or_frame = (int)(game_sprite_base + ENEMY_ATTACK_FLASH_OFFSET);
            image_buffer_cursor->x = ENEMY_DRAW_X;
            image_buffer_cursor->y = ENEMY_DRAW_Y;
            image_buffer_cursor->flags = 0;
            ++image_buffer_cursor;
            emitted_effect = 1;
            --attack_frame_count;
            if (attack_frame_count <= 0) {
                attack_frame_count = 7;
                projectile_dx = ((mouse_x_average_recent - monster_x) << 4) / 0x28;
                projectile_dy = ((random_in_range(-0x1e, 0x1e) + (mouse_y_mean_recent - monster_y)) << 4) / 0x28;
                spawn_auxiliary_projectile(PROJECTILE_TARGET_PLAYER, enemy_pattern, monster_x, monster_y, projectile_dx, projectile_dy, (int)enemy_projectile_animation_frames);
                if (remaining_level_time > 0) {
                    submit_audio_request(AUDIO_CUE_ENEMY_FIRE);
                }
                --attack_cooldown;
                if (attack_cooldown <= 0) {
                    attack_delay -= 2;
                    enemy_attack_timer = attack_delay;
                    attack_cooldown = enemy_attack_interval;
                    --enemy_fire_acceleration;
                    if (enemy_fire_acceleration <= 0) {
                        ++enemy_attack_interval;
                        enemy_fire_acceleration = 0xf;
                    }
                }
            }
        }
        if (!emitted_effect) {
            if (enemy_attack_timer < 0xf || (attack_delay - 0x14) < enemy_attack_timer) {
                image_buffer_cursor->sprite_or_frame = (int)(game_sprite_base + ENEMY_ATTACK_WINDUP_OFFSET);
                image_buffer_cursor->x = ENEMY_DRAW_X;
                image_buffer_cursor->y = ENEMY_DRAW_Y;
                image_buffer_cursor->flags = 0;
                ++image_buffer_cursor;
            } else {
                image_buffer_cursor->sprite_or_frame = (int)(game_sprite_base + ENEMY_IDLE_SPRITE_OFFSET);
                image_buffer_cursor->x = ENEMY_DRAW_X;
                image_buffer_cursor->y = ENEMY_DRAW_Y;
                image_buffer_cursor->flags = 0;
                ++image_buffer_cursor;
            }
        }
        return;
    }
    image_buffer_cursor->sprite_or_frame = (int)(game_sprite_base + ENEMY_ATTACK_FLASH_OFFSET);
    image_buffer_cursor->x = ENEMY_DRAW_X;
    image_buffer_cursor->y = ENEMY_DRAW_Y;
    image_buffer_cursor->flags = 0;
    ++image_buffer_cursor;
}
