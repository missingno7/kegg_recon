int run_level(void)
{
    level_intro_ticks = LEVEL_INTRO_GRACE_TICKS;
    hud_flash_ticks = 0;
    old_display_mode = vga_state.viewport_bottom_or_height;
    vga_state.viewport_bottom_or_height = LEVEL_HUD_BOTTOM;
    fade_dac((void *)vga_buffer_base, 0, VGA_DAC_MAX_COMPONENT, 8);
    file_buf_ptr = file_error_state;
    load_monster_art();
    prep_level();
    *(unsigned char *)&hook_flags_word &= 0xf8;
    set_image_pages((int)sprite_commands, 0x100, 4, (int)front_page_bufs, (int)back_page_queue);
    initialize_level_hud();
    zapbol();
    sprclr();
    aitune();
    wait_for_tick(0);
    wait_for_tick(0);
    plot_transformed_pixel((void *)sprite_memory_base, page2);
    copy_screen_span_entry(page2, 0, src_page, 0, vga_state.buffer_size_or_draw_parameter);
    copy_screen_span_entry(page2, 0, dst_page, 0, vga_state.buffer_size_or_draw_parameter);
    page_idx = page2;
    scan();
    update_enemy_attack_cycle();
    firein();
    fade_dac((void *)vga_buffer_base, VGA_DAC_MAX_COMPONENT, 0, 1);
    do {
        wait_for_tick(3);
        update_level_hud();
        handle_s_key();
        update_enemy_attack_cycle();
        update_auxiliary_projectiles();
        firein();
        animate();
        redraw_image_region(0, 0);
        if (image_buffer_error_code) {
            fatal_exit(image_buffer_error_code, 0);
        }
        show_page();
        if (enemy_health_current <= 0 || remaining_level_time <= 0) {
            --level_intro_ticks;
            --enemy_shot_countdown;
            if (enemy_shot_countdown <= 0) {
                if (enemy_health_current <= 0) {
                    if (!audio_stream_flag) {
                        submit_audio_request(AUDIO_CUE_ENEMY_DEFEATED);
                    }
                    for (enemy_shot_countdown = 0; enemy_shot_countdown < 2; ++enemy_shot_countdown) {
                        spawn_animated_sprite(random_in_range(-0x1e, 0x1e) + 0x106, random_in_range(-0x1e, 0x1e) + 0x56, 0, 0, (int)game_sprite_base, (int)bolt_impact_animation_frames, 1);
                    }
                    enemy_shot_countdown = 8;
                } else {
                    if (!audio_stream_flag) {
                        submit_audio_request(AUDIO_CUE_TIME_EXPIRED);
                    }
                    spawn_animated_sprite(random_in_range(-0x10, 0x10) + (mouse_x_average_recent + 4), (mouse_y_mean_recent + 8) + random_in_range(-0x10, 0x10), 0, 0, (int)game_sprite_base, (int)bolt_impact_animation_frames, 1);
                    enemy_shot_countdown = 0x19;
                }
            }
        }
        if (enemy_health_current <= 0 && level_intro_ticks <= 0) {
            restore_gameplay_display_mode();
            return award_level_completion_bonus();
        }
    } while (level_intro_ticks > 0 && (current_scan_code == keyboard_scan_byte || keyboard_scan_byte != 1));
    restore_gameplay_display_mode();
    return fade_level_to_white();
}

void restore_gameplay_display_mode(void) { vga_state.viewport_bottom_or_height = old_display_mode; }

int fade_level_to_white(void)
{
    submit_audio_request(AUDIO_CUE_GAME_OVER);
    palette_fade_delay_ticks = 2;
    for (work_value = 0; work_value < 0x3f; ++work_value) {
        for (temp = 0; temp < VGA_PALETTE_COMPONENT_BYTES; temp += 3) {
            if (++*(unsigned char *)(unsigned char *)(vga_buffer_base + temp) > VGA_DAC_MAX_COMPONENT)
                *(unsigned char *)(unsigned char *)(vga_buffer_base + temp) = VGA_DAC_MAX_COMPONENT;
        }
        write_vga_palette((void *)vga_buffer_base);
        wait_for_tick(3);
    }
    palette_fade_delay_ticks = 1;
    return 0;
}

int award_level_completion_bonus(void)
{
    submit_audio_request(AUDIO_CUE_LEVEL_COMPLETE);
    if (arcade == 0)
        score_state->score += (LEVEL_COMPLETION_BONUS_POINTS / total_level_time) * remaining_level_time + LEVEL_COMPLETION_BONUS_POINTS;
    palette_fade_delay_ticks = 3;
    fade_dac(vga_buffer_base, 0, -VGA_DAC_MAX_COMPONENT, -1);
    palette_fade_delay_ticks = 1;
    return 1;
}

/* Record the first brick x coordinate on each screen row. */
void scan(void)
{
    int screen_x;
    int screen_y;
    int tile_code;
    for (screen_y = 0; screen_y < LEVEL_HUD_BOTTOM; screen_y++) {
        for (screen_x = BRICK_ROW_SCAN_X_START; screen_x < BRICK_ROW_SCAN_X_END; screen_x += BRICK_ROW_SCAN_STEP) {
            tile_code = (unsigned char)read_vga_pixel_entry(screen_x, screen_y);
            if (tile_code >= 0x18 && tile_code <= 0x27) {
                open_brick_x_by_row[screen_y] = screen_x;
                break;
            }
            if (tile_code >= 0x50 && tile_code <= 0x58) {
                open_brick_x_by_row[screen_y] = screen_x;
                break;
            }
            if (tile_code >= 0x90 && tile_code <= 0xa7) {
                open_brick_x_by_row[screen_y] = screen_x;
                break;
            }
        }
    }
}

