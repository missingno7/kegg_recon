#define CHEAT_LEVEL_KEYS 0x02
#define CHEAT_STICKY_RACKET 0x04
#define CHEAT_EXTRA_LIVES 0x08
#define KEY_ASCII_UPPER_A 0x41
#define KEY_ASCII_UPPER_Z 0x5a
#define KEY_ASCII_PERCENT 0x25
