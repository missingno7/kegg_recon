extern void update_racket_movement_bounds(void);

void handle_keyboard_controls(void)
{
    if (keyboard_cheat_flags & CHEAT_SPELL_KEYS) {
        if (current_ascii >= KEY_ASCII_UPPER_A && current_ascii <= KEY_ASCII_UPPER_Z &&
            (keyboard_scan_byte & KEYBOARD_RELEASE_BIT) == 0)
            spawn_falling_spell((unsigned char)(current_ascii - KEY_ASCII_UPPER_A), 0,
                                CHEAT_SPELL_SPAWN_X, CHEAT_SPELL_SPAWN_Y);
        if (current_ascii == KEY_ASCII_PERCENT && (keyboard_scan_byte & KEYBOARD_RELEASE_BIT) == 0)
            spawn_falling_spell(CHEAT_SPECIAL_SPELL_ID, 0, CHEAT_SPELL_SPAWN_X, CHEAT_SPELL_SPAWN_Y);
        if (current_ascii == KEY_ASCII_PERIOD && (keyboard_scan_byte & KEYBOARD_RELEASE_BIT) == 0) {
            player_key_flags->control_flags &= (unsigned char)~PLAYER_FLAG_CATCH_BALL;
            player_key_flags->spell_flags &= (unsigned char)~SPELL_FLAG_TEMPORARY;
            player_key_flags->control_flags &= (unsigned char)~PLAYER_FLAG_BONUS_SIGNAL;
            player_key_flags->control_flags &= (unsigned char)~PLAYER_FLAG_RACKET_EFFECT;
            update_racket_movement_bounds();
        }
    }

    if (keyboard_cheat_flags & CHEAT_LEVEL_KEYS) {
        if (keyboard_scan_byte == KEY_SCAN_ESCAPE) {
            level_number = CHEAT_LEVEL_NUMBER;
            spell_count = 0;
            remaining_brick_count = 0;
            current_ascii = 0;
        }
        if (prior_key_ascii != KEY_ASCII_SPACE && current_ascii == KEY_ASCII_SPACE) {
            spell_count = 0;
            remaining_brick_count = 0;
        }
        if (prior_key_ascii != KEY_ASCII_ASTERISK && current_ascii == KEY_ASCII_ASTERISK) {
            level_number += CHEAT_LEVEL_SKIP;
            spell_count = 0;
            remaining_brick_count = 0;
        }
    }
    if (keyboard_cheat_flags & CHEAT_STICKY_RACKET) {
        player_key_flags->control_flags |= PLAYER_FLAG_CATCH_BALL;
        racket_object->effect_state = RACKET_STICKY_EFFECT;
    }
    if (keyboard_cheat_flags & CHEAT_EXTRA_LIVES)
        score_state->life_balance = CHEAT_LIFE_BALANCE;
}
